export const generateLeanCanvasPDF = async (data: LeanCanvasData): Promise<void> => {
  const pdf = new jsPDF('landscape', 'mm', 'a4');
  const pageWidth = pdf.internal.pageSize.getWidth();
  const pageHeight = pdf.internal.pageSize.getHeight();
  
  // Colors
  const primaryColor = '#3B82F6';
  const secondaryColor = '#6B7280';
  const backgroundColor = '#F9FAFB';
  
  // Header
  pdf.setFillColor(59, 130, 246); // Blue
  pdf.rect(0, 0, pageWidth, 25, 'F');
  
  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(20);
  pdf.setFont('helvetica', 'bold');
  pdf.text('Lean Canvas', 15, 17);
  
  pdf.setFontSize(12);
  pdf.setFont('helvetica', 'normal');
  pdf.text(`Generated by Bizactly.AI • ${data.createdDate}`, pageWidth - 80, 17);
  
  // Product Name
  pdf.setTextColor(59, 130, 246);
  pdf.setFontSize(16);
  pdf.setFont('helvetica', 'bold');
  pdf.text(data.productName, 15, 35);
  
  // Canvas Grid
  const startY = 45;
  const boxHeight = 35;
  const boxWidth = (pageWidth - 30) / 3;
  
  // Helper function to draw canvas box
  const drawCanvasBox = (x: number, y: number, width: number, height: number, title: string, content: string) => {
    // Box border
    pdf.setDrawColor(229, 231, 235);
    pdf.setLineWidth(0.5);
    pdf.rect(x, y, width, height);
    
    // Title background
    pdf.setFillColor(249, 250, 251);
    pdf.rect(x, y, width, 8, 'F');
    
    // Title
    pdf.setTextColor(55, 65, 81);
    pdf.setFontSize(10);
    pdf.setFont('helvetica', 'bold');
    pdf.text(title, x + 2, y + 5.5);
    
    // Content
    pdf.setTextColor(75, 85, 99);
    pdf.setFontSize(9);
    pdf.setFont('helvetica', 'normal');
    
    const lines = pdf.splitTextToSize(content, width - 4);
    let textY = y + 12;
    lines.forEach((line: string) => {
      if (textY < y + height - 2) {
        pdf.text(line, x + 2, textY);
        textY += 4;
      }
    });
  };
  
  // Row 1
  drawCanvasBox(15, startY, boxWidth, boxHeight, '1. Problem', data.problem);
  drawCanvasBox(15 + boxWidth, startY, boxWidth, boxHeight, '4. Solution', data.solution);
  drawCanvasBox(15 + boxWidth * 2, startY, boxWidth, boxHeight, '3. Unique Value Proposition', data.uniqueValueProposition);
  
  // Row 2
  drawCanvasBox(15, startY + boxHeight, boxWidth, boxHeight, '8. Key Metrics', data.keyMetrics);
  drawCanvasBox(15 + boxWidth, startY + boxHeight, boxWidth, boxHeight, '5. Channels', data.channels);
  drawCanvasBox(15 + boxWidth * 2, startY + boxHeight, boxWidth, boxHeight, '2. Customer Segments', data.customerSegments);
  
  // Row 3
  drawCanvasBox(15, startY + boxHeight * 2, boxWidth, boxHeight, '7. Cost Structure', data.costStructure);
  drawCanvasBox(15 + boxWidth, startY + boxHeight * 2, boxWidth, boxHeight, '9. Unfair Advantage', data.unfairAdvantage);
  drawCanvasBox(15 + boxWidth * 2, startY + boxHeight * 2, boxWidth, boxHeight, '6. Revenue Streams', data.revenueStreams);
  
  // Footer
  pdf.setTextColor(107, 114, 128);
  pdf.setFontSize(8);
  pdf.text('Created with Bizactly.AI - Your AI-Powered Startup Coach', 15, pageHeight - 10);
  
  // Save PDF
  pdf.save(`${data.productName.replace(/[^a-z0-9]/gi, '_').toLowerCase()}_lean_canvas.pdf`);
};

export const generateMVPPlanPDF = async (data: MVPPlanData): Promise<void> => {
  const pdf = new jsPDF('portrait', 'mm', 'a4');
  const pageWidth = pdf.internal.pageSize.getWidth();
  const pageHeight = pdf.internal.pageSize.getHeight();
  let currentY = 20;
  
  // Header
  pdf.setFillColor(59, 130, 246);
  pdf.rect(0, 0, pageWidth, 25, 'F');
  
  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(20);
  pdf.setFont('helvetica', 'bold');
  pdf.text('MVP Development Plan', 15, 17);
  
  pdf.setFontSize(10);
  pdf.text(`Generated by Bizactly.AI • ${data.createdDate}`, pageWidth - 70, 17);
  
  currentY = 35;
  
  // Project Overview
  pdf.setTextColor(59, 130, 246);
  pdf.setFontSize(16);
  pdf.setFont('helvetica', 'bold');
  pdf.text(data.projectName, 15, currentY);
  currentY += 10;
  
  // Target Audience
  pdf.setTextColor(75, 85, 99);
  pdf.setFontSize(10);
  pdf.setFont('helvetica', 'bold');
  pdf.text('Target Audience:', 15, currentY);
  pdf.setFont('helvetica', 'normal');
  pdf.text(data.targetAudience, 50, currentY);
  currentY += 8;
  
  // Value Proposition
  pdf.setFont('helvetica', 'bold');
  pdf.text('Value Proposition:', 15, currentY);
  pdf.setFont('helvetica', 'normal');
  const vpLines = pdf.splitTextToSize(data.coreValueProposition, pageWidth - 30);
  pdf.text(vpLines, 15, currentY + 5);
  currentY += vpLines.length * 4 + 10;
  
  // Timeline Overview
  pdf.setTextColor(59, 130, 246);
  pdf.setFontSize(14);
  pdf.setFont('helvetica', 'bold');
  pdf.text('Development Timeline', 15, currentY);
  currentY += 8;
  
  pdf.setTextColor(75, 85, 99);
  pdf.setFontSize(10);
  pdf.text(`Total Estimated Duration: ${data.totalEstimatedDays} days`, 15, currentY);
  currentY += 10;
  
  // Features by Priority
  pdf.setTextColor(59, 130, 246);
  pdf.setFontSize(12);
  pdf.setFont('helvetica', 'bold');
  pdf.text('Feature Breakdown', 15, currentY);
  currentY += 8;
  
  // Group features by priority
  const highPriority = data.features.filter(f => f.priority === 'high');
  const mediumPriority = data.features.filter(f => f.priority === 'medium');
  const lowPriority = data.features.filter(f => f.priority === 'low');
  
  const drawFeatureSection = (title: string, features: typeof data.features, color: string) => {
    if (features.length === 0) return;
    
    pdf.setTextColor(75, 85, 99);
    pdf.setFontSize(11);
    pdf.setFont('helvetica', 'bold');
    pdf.text(title, 15, currentY);
    currentY += 6;
    
    features.forEach((feature, index) => {
      if (currentY > pageHeight - 30) {
        pdf.addPage();
        currentY = 20;
      }
      
      // Feature name
      pdf.setTextColor(55, 65, 81);
      pdf.setFontSize(10);
      pdf.setFont('helvetica', 'bold');
      pdf.text(`${index + 1}. ${feature.name}`, 20, currentY);
      currentY += 5;
      
      // Feature description
      pdf.setFont('helvetica', 'normal');
      pdf.setFontSize(9);
      const descLines = pdf.splitTextToSize(feature.description, pageWidth - 50);
      pdf.text(descLines, 25, currentY);
      currentY += descLines.length * 3.5;
      
      // Feature details
      pdf.setTextColor(107, 114, 128);
      pdf.setFontSize(8);
      pdf.text(`Effort: ${feature.effort} | Impact: ${feature.impact} | Est. ${feature.estimatedDays} days`, 25, currentY);
      currentY += 8;
    });
    
    currentY += 5;
  };
  
  drawFeatureSection('🔴 High Priority Features', highPriority, '#EF4444');
  drawFeatureSection('🟡 Medium Priority Features', mediumPriority, '#F59E0B');
  drawFeatureSection('🟢 Low Priority Features', lowPriority, '#10B981');
  
  // Recommendations
  if (data.recommendations.length > 0) {
    if (currentY > pageHeight - 50) {
      pdf.addPage();
      currentY = 20;
    }
    
    pdf.setTextColor(59, 130, 246);
    pdf.setFontSize(12);
    pdf.setFont('helvetica', 'bold');
    pdf.text('Strategic Recommendations', 15, currentY);
    currentY += 8;
    
    data.recommendations.forEach((rec, index) => {
      if (currentY > pageHeight - 20) {
        pdf.addPage();
        currentY = 20;
      }
      
      pdf.setTextColor(75, 85, 99);
      pdf.setFontSize(9);
      pdf.setFont('helvetica', 'normal');
      const recLines = pdf.splitTextToSize(`${index + 1}. ${rec}`, pageWidth - 30);
      pdf.text(recLines, 15, currentY);
      currentY += recLines.length * 4 + 3;
    });
  }
  
  // Footer
  pdf.setTextColor(107, 114, 128);
  pdf.setFontSize(8);
  pdf.text('Created with Bizactly.AI - Your AI-Powered Startup Coach', 15, pageHeight - 10);
  
  // Save PDF
  pdf.save(`${data.projectName.replace(/[^a-z0-9]/gi, '_').toLowerCase()}_mvp_plan.pdf`);
};

export const generateCanvasFromChatData = (chatHistory: string, productName: string): LeanCanvasData => {
  // Extract canvas data from chat history using simple text parsing
  const extractSection = (sectionName: string): string => {
    const regex = new RegExp(`${sectionName}[:\\s]*([^\\n]*(?:\\n(?!\\*\\*)[^\\n]*)*)`, 'i');
    const match = chatHistory.match(regex);
    return match ? match[1].trim() : '';
  };
  
  return {
    problem: extractSection('Problem|Problems'),
    customerSegments: extractSection('Customer Segments?|Target Customers?'),
    uniqueValueProposition: extractSection('Value Proposition|Unique Value'),
    solution: extractSection('Solution'),
    channels: extractSection('Channels?|Distribution'),
    revenueStreams: extractSection('Revenue Streams?|Monetization'),
    costStructure: extractSection('Cost Structure|Costs'),
    keyMetrics: extractSection('Key Metrics|Metrics'),
    unfairAdvantage: extractSection('Unfair Advantage|Competitive Advantage'),
    productName: productName || 'My Startup',
    createdDate: new Date().toLocaleDateString()
  };
};

export const generateMVPFromChatData = (chatHistory: string, productName: string): MVPPlanData => {
  // Extract MVP data from chat history
  const extractFeatures = (): MVPPlanData['features'] => {
    const features: MVPPlanData['features'] = [];
    const featureRegex = /(?:feature|functionality)[:\s]*([^\\n]+)/gi;
    let match;
    let index = 1;
    
    while ((match = featureRegex.exec(chatHistory)) !== null && features.length < 10) {
      features.push({
        name: `Feature ${index}`,
        description: match[1].trim(),
        priority: index <= 3 ? 'high' : index <= 6 ? 'medium' : 'low',
        effort: index <= 3 ? 'high' : 'medium',
        impact: index <= 3 ? 'high' : 'medium',
        estimatedDays: Math.floor(Math.random() * 14) + 7
      });
      index++;
    }
    
    return features;
  };
  
  const extractRecommendations = (): string[] => {
    const recommendations: string[] = [];
    const recRegex = /(?:recommend|suggest|should)[:\s]*([^\\n]+)/gi;
    let match;
    
    while ((match = recRegex.exec(chatHistory)) !== null && recommendations.length < 5) {
      recommendations.push(match[1].trim());
    }
    
    return recommendations;
  };
  
  const features = extractFeatures();
  const totalDays = features.reduce((sum, f) => sum + f.estimatedDays, 0);
  
  return {
    projectName: productName || 'My MVP',
    targetAudience: 'Target customers identified in chat',
    coreValueProposition: 'Value proposition discussed in conversation',
    features,
    timeline: {
      phase1: features.filter(f => f.priority === 'high').map(f => f.name),
      phase2: features.filter(f => f.priority === 'medium').map(f => f.name),
      phase3: features.filter(f => f.priority === 'low').map(f => f.name)
    },
    totalEstimatedDays: totalDays,
    recommendations: extractRecommendations(),
    createdDate: new Date().toLocaleDateString()
  };
};