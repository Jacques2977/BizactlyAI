import React, { useState } from 'react';
import { Rocket, Target, Clock, TrendingUp, CheckCircle, AlertCircle, Lightbulb } from 'lucide-react';
import { generateMVPPlan, prioritizeFeatures, MVPPlan, MVPFeature } from '../api/mvpPlanner';

interface MVPPlannerProps {
  onClose: () => void;
}

export const MVPPlanner: React.FC<MVPPlannerProps> = ({ onClose }) => {
  const [formData, setFormData] = useState({
    projectDescription: '',
    targetAudience: '',
    budget: '',
    timeline: '',
  });
  const [mvpPlan, setMvpPlan] = useState<MVPPlan | null>(null);
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState('');

  const handleInputChange = (e: React.ChangeEvent<HTMLInputElement | HTMLTextAreaElement>) => {
    setFormData(prev => ({
      ...prev,
      [e.target.name]: e.target.value,
    }));
  };

  const handleGeneratePlan = async (e: React.FormEvent) => {
    e.preventDefault();
    setIsLoading(true);
    setError('');

    try {
      const plan = await generateMVPPlan(
        formData.projectDescription,
        formData.targetAudience,
        formData.budget,
        formData.timeline
      );
      setMvpPlan(plan);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to generate MVP plan');
    } finally {
      setIsLoading(false);
    }
  };

  // Export and sharing functions for MVP Plan
  const copyMVPToClipboard = async () => {
    if (!mvpPlan) return;
    
    const mvpText = generateMVPText();
    try {
      await navigator.clipboard.writeText(mvpText);
      console.log('MVP Plan copied to clipboard!');
    } catch (err) {
      console.error('Failed to copy to clipboard:', err);
    }
  };

  const generateMVPText = () => {
    if (!mvpPlan) return '';
    
    let mvpText = `MVP DEVELOPMENT PLAN\n${'='.repeat(50)}\n\n`;
    mvpText += `Project: ${mvpPlan.projectName}\n`;
    mvpText += `Target Audience: ${mvpPlan.targetAudience}\n`;
    mvpText += `Timeline: ${mvpPlan.totalEstimatedDays} days\n\n`;
    
    mvpText += `VALUE PROPOSITION:\n${'-'.repeat(20)}\n${mvpPlan.coreValueProposition}\n\n`;
    
    mvpText += `FEATURES BREAKDOWN:\n${'-'.repeat(20)}\n`;
    mvpPlan.features.forEach((feature, index) => {
      mvpText += `${index + 1}. ${feature.name} (${feature.priority} priority)\n`;
      mvpText += `   ${feature.description}\n`;
      mvpText += `   Effort: ${feature.effort} | Impact: ${feature.impact} | Est: ${feature.estimatedDays} days\n\n`;
    });
    
    mvpText += `RECOMMENDATIONS:\n${'-'.repeat(20)}\n`;
    mvpPlan.recommendations.forEach((rec, index) => {
      mvpText += `${index + 1}. ${rec}\n`;
    });
    
    mvpText += `\nGenerated by Bizactly.AI on ${new Date().toLocaleDateString()}`;
    return mvpText;
  };

  const exportMVPToPDF = async () => {
    if (!mvpPlan) return;
    
    const { generateMVPPlanPDF } = await import('../utils/pdfGenerator');
    const mvpData = {
      projectName: mvpPlan.projectName,
      targetAudience: mvpPlan.targetAudience,
      coreValueProposition: mvpPlan.coreValueProposition,
      features: mvpPlan.features,
      timeline: mvpPlan.timeline,
      totalEstimatedDays: mvpPlan.totalEstimatedDays,
      recommendations: mvpPlan.recommendations,
      createdDate: new Date().toLocaleDateString()
    };
    
    await generateMVPPlanPDF(mvpData);
  };

  const exportMVPToJSON = () => {
    if (!mvpPlan) return;
    
    const mvpData = {
      ...mvpPlan,
      metadata: {
        exportedAt: new Date().toISOString(),
        tool: 'Bizactly.AI MVP Planner'
      }
    };
    
    const dataStr = JSON.stringify(mvpData, null, 2);
    const dataBlob = new Blob([dataStr], { type: 'application/json' });
    const url = URL.createObjectURL(dataBlob);
    const link = document.createElement('a');
    link.href = url;
    link.download = 'mvp_plan.json';
    link.click();
    URL.revokeObjectURL(url);
  };

  // Third-party sharing functions for MVP
  const shareToJira = () => {
    if (!mvpPlan) return;
    const mvpText = generateMVPText();
    navigator.clipboard.writeText(mvpText);
    alert('MVP Plan copied to clipboard! You can now create tickets in Jira with this information.');
  };

  const shareToAsana = () => {
    if (!mvpPlan) return;
    const mvpText = generateMVPText();
    navigator.clipboard.writeText(mvpText);
    window.open('https://asana.com', '_blank');
    alert('MVP Plan copied to clipboard! Create a new project in Asana and paste the content.');
  };

  const shareToLinear = () => {
    if (!mvpPlan) return;
    const mvpText = generateMVPText();
    navigator.clipboard.writeText(mvpText);
    window.open('https://linear.app', '_blank');
    alert('MVP Plan copied to clipboard! Create issues in Linear with this information.');
  };

  const shareToGitHub = () => {
    if (!mvpPlan) return;
    const mvpText = generateMVPText();
    navigator.clipboard.writeText(mvpText);
    alert('MVP Plan copied to clipboard! You can now create GitHub issues or add to your project README.');
  };

  const getPriorityColor = (priority: string) => {
    switch (priority) {
      case 'high': return 'bg-red-100 text-red-800 border-red-200';
      case 'medium': return 'bg-yellow-100 text-yellow-800 border-yellow-200';
      case 'low': return 'bg-green-100 text-green-800 border-green-200';
      default: return 'bg-gray-100 text-gray-800 border-gray-200';
    }
  };

  const getEffortColor = (effort: string) => {
    switch (effort) {
      case 'high': return 'bg-red-50 text-red-700';
      case 'medium': return 'bg-yellow-50 text-yellow-700';
      case 'low': return 'bg-green-50 text-green-700';
      default: return 'bg-gray-50 text-gray-700';
    }
  };

  const getImpactColor = (impact: string) => {
    switch (impact) {
      case 'high': return 'bg-blue-50 text-blue-700';
      case 'medium': return 'bg-indigo-50 text-indigo-700';
      case 'low': return 'bg-purple-50 text-purple-700';
      default: return 'bg-gray-50 text-gray-700';
    }
  };

  return (
    <div className="flex flex-col h-full bg-gray-900">
      {/* Header */}
      <div className="flex items-center justify-between p-6 border-b border-gray-700 bg-gradient-to-r from-purple-500 to-pink-600">
        <div className="flex items-center space-x-3">
          <Rocket className="w-8 h-8 text-white" />
          <div>
            <h3 className="text-xl font-bold text-white">MVP Planner</h3>
            <p className="text-purple-100 text-sm">Plan your Minimum Viable Product</p>
          </div>
        </div>
        <button
          onClick={onClose}
          className="text-white hover:text-purple-200 transition-colors text-xl"
        >
          ✕
        </button>
      </div>

      <div className="flex-1 overflow-y-auto p-6 bg-gray-900">
        {!mvpPlan ? (
          /* Input Form */
          <form onSubmit={handleGeneratePlan} className="space-y-6">
            <div>
              <label className="block text-sm font-semibold text-gray-300 mb-2">
                Project Description *
              </label>
              <textarea
                name="projectDescription"
                value={formData.projectDescription}
                onChange={handleInputChange}
                required
                rows={4}
                className="w-full bg-gray-800 border border-gray-600 rounded-lg px-4 py-3 text-white focus:outline-none focus:ring-2 focus:ring-purple-500 focus:border-transparent"
                placeholder="Describe your startup idea, what problem it solves, and how it works..."
              />
            </div>

            <div>
              <label className="block text-sm font-semibold text-gray-300 mb-2">
                Target Audience *
              </label>
              <input
                type="text"
                name="targetAudience"
                value={formData.targetAudience}
                onChange={handleInputChange}
                required
                className="w-full bg-gray-800 border border-gray-600 rounded-lg px-4 py-3 text-white focus:outline-none focus:ring-2 focus:ring-purple-500 focus:border-transparent"
                placeholder="Who are your primary users? (e.g., small business owners, freelancers, students)"
              />
            </div>

            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              <div>
                <label className="block text-sm font-semibold text-gray-300 mb-2">
                  Budget (Optional)
                </label>
                <input
                  type="text"
                  name="budget"
                  value={formData.budget}
                  onChange={handleInputChange}
                  className="w-full bg-gray-800 border border-gray-600 rounded-lg px-4 py-3 text-white focus:outline-none focus:ring-2 focus:ring-purple-500 focus:border-transparent"
                  placeholder="e.g., $10,000, Limited budget, etc."
                />
              </div>

              <div>
                <label className="block text-sm font-semibold text-gray-300 mb-2">
                  Timeline (Optional)
                </label>
                <input
                  type="text"
                  name="timeline"
                  value={formData.timeline}
                  onChange={handleInputChange}
                  className="w-full bg-gray-800 border border-gray-600 rounded-lg px-4 py-3 text-white focus:outline-none focus:ring-2 focus:ring-purple-500 focus:border-transparent"
                  placeholder="e.g., 3 months, ASAP, 6 weeks, etc."
                />
              </div>
            </div>

            {error && (
              <div className="bg-red-900/30 border border-red-700/50 text-red-200 px-4 py-3 rounded-lg">
                {error}
              </div>
            )}

            <button
              type="submit"
              disabled={isLoading}
              className="w-full bg-gradient-to-r from-purple-500 to-pink-600 text-white py-3 rounded-lg font-semibold hover:shadow-lg transition-all duration-300 disabled:opacity-50 disabled:cursor-not-allowed"
            >
              {isLoading ? (
                <div className="flex items-center justify-center space-x-2">
                  <div className="w-5 h-5 border-2 border-white border-t-transparent rounded-full animate-spin"></div>
                  <span>Generating MVP Plan...</span>
                </div>
              ) : (
                'Generate MVP Plan'
              )}
            </button>
          </form>
        ) : (
          /* MVP Plan Results */
          <div className="space-y-6">
            {/* Plan Overview */}
            <div className="bg-gradient-to-r from-purple-900/30 to-pink-900/30 border border-purple-700/50 rounded-lg p-6">
              <h3 className="text-2xl font-bold text-white mb-2">{mvpPlan.projectName}</h3>
              <div className="grid grid-cols-1 md:grid-cols-2 gap-4 mb-4">
                <div className="flex items-center space-x-2">
                  <Target className="w-5 h-5 text-purple-600" />
                  <span className="text-sm font-medium text-gray-300">Target Audience:</span>
                  <span className="text-sm text-gray-400">{mvpPlan.targetAudience}</span>
                </div>
                <div className="flex items-center space-x-2">
                  <Clock className="w-5 h-5 text-purple-600" />
                  <span className="text-sm font-medium text-gray-300">Estimated Timeline:</span>
                  <span className="text-sm text-gray-400">{mvpPlan.totalEstimatedDays} days</span>
                </div>
              </div>
              <div className="bg-gray-800 rounded-lg p-4 border border-purple-700/30">
                <h4 className="font-semibold text-white mb-2">Core Value Proposition:</h4>
                <p className="text-gray-300">{mvpPlan.coreValueProposition}</p>
              </div>
            </div>

            {/* Features List */}
            <div className="bg-gray-800 border border-gray-700 rounded-lg p-6">
              <h4 className="text-xl font-bold text-white mb-4 flex items-center">
                <CheckCircle className="w-6 h-6 text-green-600 mr-2" />
                Feature Breakdown ({mvpPlan.features.length} features)
              </h4>
              <div className="space-y-4">
                {mvpPlan.features.map((feature) => (
                  <div key={feature.id} className="border border-gray-600 rounded-lg p-4 hover:shadow-sm transition-shadow bg-gray-700/30">
                    <div className="flex items-start justify-between mb-2">
                      <h5 className="font-semibold text-white">{feature.name}</h5>
                      <div className="flex space-x-2">
                        <span className={`px-2 py-1 rounded-full text-xs font-medium border ${getPriorityColor(feature.priority)}`}>
                          {feature.priority} priority
                        </span>
                        <span className={`px-2 py-1 rounded-full text-xs font-medium ${getEffortColor(feature.effort)}`}>
                          {feature.effort} effort
                        </span>
                        <span className={`px-2 py-1 rounded-full text-xs font-medium ${getImpactColor(feature.impact)}`}>
                          {feature.impact} impact
                        </span>
                      </div>
                    </div>
                    <p className="text-gray-300 text-sm mb-2">{feature.description}</p>
                    <div className="flex items-center justify-between text-xs text-gray-400 mt-3">
                      <span className="capitalize">{feature.category} feature</span>
                      <span>{feature.estimatedDays} days estimated</span>
                    </div>
                  </div>
                ))}
              </div>
            </div>

            {/* Development Timeline */}
            <div className="bg-gray-800 border border-gray-700 rounded-lg p-6">
              <h4 className="text-xl font-bold text-white mb-4 flex items-center">
                <TrendingUp className="w-6 h-6 text-blue-600 mr-2" />
                Development Timeline
              </h4>
              <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
                {Object.entries(mvpPlan.timeline).map(([phase, featureIds]) => (
                  <div key={phase} className="bg-gray-700/50 rounded-lg p-4">
                    <h5 className="font-semibold text-white mb-3 capitalize">
                      {phase.replace(/(\d+)/, ' $1')}
                    </h5>
                    <div className="space-y-2">
                      {featureIds.map((featureId) => {
                        const feature = mvpPlan.features.find(f => f.id === featureId);
                        return feature ? (
                          <div key={featureId} className="text-sm">
                            <div className="font-medium text-gray-300">{feature.name}</div>
                            <div className="text-gray-400">{feature.estimatedDays} days</div>
                          </div>
                        ) : null;
                      })}
                    </div>
                  </div>
                ))}
              </div>
            </div>

            {/* Recommendations */}
            <div className="bg-yellow-900/30 border border-yellow-700/50 rounded-lg p-6">
              <h4 className="text-xl font-bold text-white mb-4 flex items-center">
                <Lightbulb className="w-6 h-6 text-yellow-600 mr-2" />
                Strategic Recommendations
              </h4>
              <ul className="space-y-2">
                {mvpPlan.recommendations.map((recommendation, index) => (
                  <li key={index} className="flex items-start space-x-2">
                    <AlertCircle className="w-4 h-4 text-yellow-600 mt-0.5 flex-shrink-0" />
                    <span className="text-gray-300 text-sm">{recommendation}</span>
                  </li>
                ))}
              </ul>
            </div>

            {/* Action Buttons */}
            <div className="flex space-x-4">
              <button
                onClick={() => setMvpPlan(null)}
                className="flex-1 bg-gray-700 text-gray-300 py-3 rounded-lg font-semibold hover:bg-gray-600 transition-colors"
              >
                Create New Plan
              </button>
              <div className="flex-1 space-y-3">
                <div className="flex space-x-2">
                  <button
                    onClick={copyMVPToClipboard}
                    className="flex-1 bg-green-600 text-white py-2 px-3 rounded-lg font-medium hover:bg-green-700 transition-colors text-sm"
                  >
                    📋 Copy Plan
                  </button>
                  <button
                    onClick={exportMVPToPDF}
                    className="flex-1 bg-blue-600 text-white py-2 px-3 rounded-lg font-medium hover:bg-blue-700 transition-colors text-sm"
                  >
                    📄 Export PDF
                  </button>
                  <button
                    onClick={exportMVPToJSON}
                    className="flex-1 bg-purple-600 text-white py-2 px-3 rounded-lg font-medium hover:bg-purple-700 transition-colors text-sm"
                  >
                    💾 Export JSON
                  </button>
                </div>
                <div className="flex space-x-2">
                  <button
                    onClick={() => shareToJira()}
                    className="flex-1 bg-gray-700 text-white py-2 px-3 rounded-lg text-xs hover:bg-gray-600 transition-colors"
                  >
                    🎯 Jira
                  </button>
                  <button
                    onClick={() => shareToAsana()}
                    className="flex-1 bg-gray-700 text-white py-2 px-3 rounded-lg text-xs hover:bg-gray-600 transition-colors"
                  >
                    ✅ Asana
                  </button>
                  <button
                    onClick={() => shareToLinear()}
                    className="flex-1 bg-gray-700 text-white py-2 px-3 rounded-lg text-xs hover:bg-gray-600 transition-colors"
                  >
                    📐 Linear
                  </button>
                  <button
                    onClick={() => shareToGitHub()}
                    className="flex-1 bg-gray-700 text-white py-2 px-3 rounded-lg text-xs hover:bg-gray-600 transition-colors"
                  >
                    🐙 GitHub
                  </button>
                </div>
              </div>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};